test "bash: active help can be disabled" {
    const cmd = Command{
        .name = "myapp",
        .summary = "My application",
        .active_help = &.{"Help message"},
    };

    const script = try generateWithActiveHelp(&cmd, std.testing.allocator, false);
    defer std.testing.allocator.free(script);

