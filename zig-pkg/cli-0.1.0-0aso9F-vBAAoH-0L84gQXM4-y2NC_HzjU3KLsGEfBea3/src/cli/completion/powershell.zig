test "powershell: completion hides hidden subcommands" {
    const subcmd1 = Command{
        .name = "visible",
        .summary = "Visible command",
    };
    const subcmd2 = Command{
        .name = "hidden",
        .summary = "Hidden command",
        .hidden = true,
    };
    const cmd = Command{
        .name = "myapp",
        .summary = "My application",
        .subcommands = &.{ &subcmd1, &subcmd2 },
    };

    const script = try generate(&cmd, std.testing.allocator);
    defer std.testing.allocator.free(script);

    try std.testing.expect(std.mem.indexOf(u8, script, "'visible'") != null);
    // Hidden command should not appear in completions
    var found_hidden = false;
    var lines = std.mem.splitScalar(u8, script, '\n');
    while (lines.next()) |line| {
        if (std.mem.indexOf(u8, line, "CompletionResult") != null and
            std.mem.indexOf(u8, line, "'hidden'") != null)
        {
            found_hidden = true;
            break;
        }
    }
    try std.testing.expect(!found_hidden);
}

