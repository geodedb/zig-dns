test "generate powershell completion" {
    const cmd = Command{
        .name = "test",
        .summary = "Test command",
    };

    const script = try generate(&cmd, std.testing.allocator);
    defer std.testing.allocator.free(script);

    try std.testing.expect(std.mem.indexOf(u8, script, "Register-ArgumentCompleter") != null);
    try std.testing.expect(std.mem.indexOf(u8, script, "-CommandName 'test'") != null);
}

